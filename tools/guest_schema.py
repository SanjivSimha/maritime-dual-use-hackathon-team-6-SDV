"""Generate schema/guest_manifest.schema.json from the GuestManifest contract.

    uv run python -m tools.guest_schema           # rewrite the schema file
    uv run python -m tools.guest_schema --check   # exit 1 if the file is stale; writes nothing

The schema describes a resolved manifest. Raw cards in data/guests/ may write a number as
"$<id>"; shipos.data.resolve replaces it with the value from data/assumptions/ before validation.
"""

import argparse
import json
import sys

from shipos.contracts import GuestManifest
from shipos.paths import REPO_DIR

REL_PATH = "schema/guest_manifest.schema.json"
SCHEMA_PATH = REPO_DIR / REL_PATH
COMMENT = (
    "Generated by `python -m tools.guest_schema` from shipos.contracts.GuestManifest; do not edit. "
    'Validates a resolved card: raw YAML strings "$<id>" are replaced with values from '
    "data/assumptions/ (shipos.data.resolve) first."
)


def render() -> str:
    schema = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$comment": COMMENT,
        **GuestManifest.model_json_schema(),
    }
    return json.dumps(schema, indent=2) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parser.parse_args(argv)
    expected = render()
    if args.check:
        current = SCHEMA_PATH.read_text(encoding="utf-8") if SCHEMA_PATH.exists() else None
        if current != expected:
            print(f"{REL_PATH} is out of date; run: uv run python -m tools.guest_schema")
            return 1
        print(f"{REL_PATH} is up to date")
        return 0
    SCHEMA_PATH.parent.mkdir(exist_ok=True)
    SCHEMA_PATH.write_text(expected, encoding="utf-8", newline="\n")
    print(f"wrote {REL_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
